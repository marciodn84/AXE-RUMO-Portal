CREATE OR REPLACE VIEW public.portal_pedidos AS  SELECT i.id,
    p.numero_pedido,
    i.numero_item,
    p.cliente_id,
    c.nome AS cliente,
    i.codigo_material,
    i.descricao_material,
    i.fase_status_sap,
    i.status_texto,
    i.quantidade_original,
    i.quantidade_pendente,
    i.numero_nf,
    i.data_remessa,
    k.valor_unitario,
    k.moeda,
    k.icms_aliquota,
    k.ipi_aliquota,
    k.ncm,
    k.unidade,
    k.data_negocio,
    concat_ws(' '::text, p.numero_pedido, i.numero_item, c.nome, i.codigo_material, i.descricao_material, i.status_texto, i.fase_status_sap, i.numero_nf, c.cnpj) AS termos_busca,
    c.cnpj AS cnpj_faturamento,
    p.data_pedido AS data_pedido
   FROM pedido_itens i
     JOIN pedidos p ON p.id = i.pedido_id
     JOIN clientes c ON c.id = p.cliente_id
     LEFT JOIN LATERAL ( SELECT x.id,
            x.cliente_id,
            x.produto_id,
            x.item_id,
            x.numero_pedido,
            x.numero_item,
            x.origem,
            x.fonte_chave,
            x.extracao_pdf_id,
            x.documento_id,
            x.data_negocio,
            x.observado_em,
            x.cnpj_faturamento,
            x.codigo_produto,
            x.descricao,
            x.unidade,
            x.moeda,
            x.quantidade,
            x.valor_unitario,
            x.valor_total,
            x.icms_aliquota,
            x.icms_valor,
            x.ipi_aliquota,
            x.ipi_valor,
            x.ncm,
            x.cfop,
            x.contexto_fiscal,
            x.situacao_vinculo
           FROM pedido_itens_condicoes x
          WHERE x.item_id = i.id AND x.origem = 'PEDIDO_PDF'::text
          ORDER BY x.observado_em DESC, x.id DESC
         LIMIT 1) k ON true;
NOTIFY pgrst, 'reload schema';